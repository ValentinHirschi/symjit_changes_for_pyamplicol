//! A complex product whose destination shares a physical register with a source. The peephole
//! optimizer (opt level >= 1) computes `c = a * b` straight into the argument registers of a
//! call, `(%l + %t*im) := (%$ + %t*im) Times (%6 + %7*im)`, and `Reg::Left` and `Reg::Ret` are
//! the same machine register (as are `Reg::Temp` and `Reg::Right`). `times_complex` in the AVX,
//! AVX-512 and NEON SIMD generators, and `times` in the ARM fast-complex generator (with FCMA),
//! compared the logical registers and overwrote `a` before reading it: the SIMD kernels got both
//! parts (AVX, AVX-512) or the imaginary part (NEON) wrong, and the ARM fast-complex scalar
//! kernel gave `a * b = 0`. The operands are generic, so that both parts are checked; the two
//! unused re-reads of `a` and `b` are needed for the peephole optimizer to produce this shape.
//!
//! Only x86-64 compiles the program to this shape (`Node::compile_binary` loads `a` with a
//! `LoadMath`, which the peephole optimizer turns into the load into `Reg::Ret`); on aarch64
//! both factors go to registers first. The second test loads the program as saved on x86-64,
//! which reaches the ARM generators on aarch64 (and the AVX ones on x86-64).
mod common;
use common::base_config;

use anyhow::Result;
use num_complex::Complex;
use symjit::{Application, Composer, Config, Defuns, Slot, Translator};

const A: Complex<f64> = Complex::new(0.2, 0.3);
const B: Complex<f64> = Complex::new(0.5, 0.7);

/// out = exp(a * b), with `a` and `b` in temporaries; `a` and `b` are read again (unused), so
/// their registers stay forwarded.
fn compile(config: Config) -> Result<Application> {
    let mut t = Translator::new(config);
    t.set_num_params(1);
    let ca = t.append_constant(A)?;
    let cb = t.append_constant(B)?;
    t.append_assign(&Slot::Temp(0), &Slot::Const(ca))?;
    t.append_assign(&Slot::Temp(1), &Slot::Const(cb))?;
    t.append_mul(&Slot::Temp(2), &[Slot::Temp(0), Slot::Temp(1)], 0)?;
    t.append_fun(&Slot::Temp(3), "exp", &[Slot::Temp(2)], false)?;
    t.append_mul(&Slot::Out(0), &[Slot::Temp(3)], 0)?;
    t.append_mul(&Slot::Temp(4), &[Slot::Temp(0)], 0)?;
    t.append_assign(&Slot::Temp(5), &Slot::Temp(1))?;
    let mut app = t.compile()?;
    app.prepare_simd();
    Ok(app)
}

/// 1 row (scalar kernel) and 8 rows (whole SIMD blocks of 2, 4 and 8 lanes): every row is
/// exp(a * b).
fn check(app: Application, what: &str) -> Result<()> {
    let want = (A * B).exp();
    let app = app.seal()?;
    for rows in [1, 8] {
        let x = vec![Complex::new(0.5, 0.0); rows];
        let mut outs = vec![Complex::new(f64::NAN, f64::NAN); rows];
        app.evaluate_matrix(&x, &mut outs, rows);
        for (row, z) in outs.into_iter().enumerate() {
            assert!(
                (z - want).norm() <= 1e-14 * want.norm(),
                "{what}, {rows} rows, row {row}: exp(a * b) = {z} (want {want})"
            );
        }
    }
    Ok(())
}

#[test]
fn simd_complex_product_into_call_arguments() -> Result<()> {
    for opt_level in 0..=3 {
        for fast_complex in [false, true] {
            // simd512 has no effect without AVX-512 (e.g. on aarch64)
            for simd512 in [false, true] {
                let mut config = base_config();
                config.set_opt_level(opt_level);
                config.set_complex(true);
                config.set_fast_complex(fast_complex);
                config.set_simd(true);
                config.enable_simd512(simd512);
                let what = format!(
                    "opt level {opt_level}, fast_complex = {fast_complex}, simd512 = {simd512}"
                );
                check(compile(config)?, &what)?;
            }
        }
    }
    Ok(())
}

